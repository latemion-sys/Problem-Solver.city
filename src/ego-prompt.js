function egoPrompt(d){
  const lines = [];
  lines.push(`이름: ${d.name} / 등급: ${d.grade} / 성격: ${d.personality}${d.leader ? " / 사무소의 대표" : ""}`);
  lines.push(`능력치: 근력 ${d.stats.str}, 민첩 ${d.stats.agi}, 재주 ${d.stats.tec}, 의지 ${d.stats.wil}`);
  lines.push(`마음속에 간직한 것(${d.precious.kind}): ${d.precious.text}${d.precious.lost ? ` — 잃었다(${d.precious.why})` : ""}`);
  lines.push(`사무소에 온 지 ${d.days}일, 해낸 의뢰 ${d.done}건`);
  const L = d.life, cnt = [["kill","숨통을 끊고 끝낸 의뢰"],["spare","숨만 붙여 데려온 의뢰"],["escort","호위"],["chase","추적"],["search","수색"],["abno","환상체"],["hunt","뒤틀림 토벌"],["fail","실패"],["heavy","중상 이상으로 돌아온 날"],["solo","홀로 나간 의뢰"],["crew","셋 이상 함께 나간 의뢰"],["grief","먼저 떠나보낸 동료"]]
    .filter(([k])=>L[k]).map(([k,n])=>`${n} ${L[k]}`);
  lines.push(`행적: ${cnt.length ? cnt.join(", ") : "아직 거의 없음"}`);
  if(d.weapon) lines.push(`쥐어 온 무기: ${d.weapon}`);
  if(d.diary.length) lines.push(`최근의 일들:\n- ${d.diary.join("\n- ")}`);
  if(d.records.length) lines.push(`남은 기록: ${d.records.join(" / ")}`);
  return `너는 Project Moon(로보토미 코퍼레이션 · 라이브러리 오브 루이나 · 림버스 컴퍼니)의 '도시'를 무대로 한 팬게임에서, 한 해결사가 정신이 바닥난 끝에 다정한 목소리를 뿌리치고 개화 E.G.O를 피워 내는 순간을 쓴다.
개화 E.G.O는 환상체에게서 빌린 E.G.O와 달리 그 사람 자신의 자아에서 피어나 그 사람을 닮는다. 정해진 짓는 법은 없다. 그 사람이 어떻게 살아왔는지, 개화하기 전까지 무엇을 하며 어떻게 행동했는지, 무엇을 바라는지가 이름과 모습이 된다.

[이 해결사의 기록]
${lines.join("\n")}

위 기록을 끝까지 읽고, 이 사람만의 개화 E.G.O 하나를 창작하라.
- name: "개화 E.G.O::" 뒤에 붙는 낱말 하나 또는 아주 짧은 명사구. 세상에 실제로 있는 사물 · 재료 · 도구 · 현상 · 민속 · 놀이 · 직업 같은 것의 이름이 좋다. 어느 나라 말이든 되지만 반드시 한글로 적는다.
- "개화 E.G.O::이름"으로 소리 내 읽었을 때 어색하지 않고, 이 사람의 삶이 한 낱말로 응축된 느낌이어야 한다.
- 쓰지 말 것: 덕목 · 감정 · 성격을 그대로 이르는 추상어(낙천, 희망, 정의, 분노 따위), 무기 종류 이름(한손검, 대검, 창, 총 따위), 기록의 낱말을 그대로 옮긴 것(호위, 추적, 여동생, 빵집, 회중시계 따위 — 기록은 이름의 까닭이지 이름 자체가 아니다).
- 원작에 있거나 닮은 이름은 쓰지 않는다: 동백, 마름, 가스하푼, 대행, 이립, 라바크롬 상귀니스, 케츠엔, 곰방대, 밀랍날개, 오감도, 삼라염상, 타인의 사슬, 허환경, 시체자루, 작살박이, 그리고 로보토미 · 림버스의 환상체 E.G.O 이름들.
- 다음은 결만 보여 주는 예다. 그대로 쓰거나 비슷하게 만들지 않는다: 올가미, 스테일비즈크, 엑셀레이터, 아스트라페, 앙고라, 봉합, 초목껍질, 말뚝이, 역청.
- 이미 이 사무소에 있는 이름: ${d.taken.length ? d.taken.join(", ") : "없음"} — 쓰지 않는다.
- type: weapon(무기) · armor(의복) · both(무기와 의복이 함께 드러나는 일체형) · tool(도구형) 가운데 이 사람에게 맞는 하나.
- look: 드러난 모습 한두 문장. 무엇을 입고 쥐었는지, 어떻게 작동하는지를 담백하게. 과장된 수사는 쓰지 않는다. 사람의 다리와 발은 묘사하지 않는다(늘 긴 코트 차림).
- why: 이 이름이 이 사람의 어떤 삶에서 나왔는지 한 문장. 기록의 구체적인 사실을 짚는다.
먼저 속으로 후보를 여럿 떠올리고, 위 조건에 하나라도 걸리는 것은 버린 뒤, 가장 이 사람다운 하나만 골라라.
JSON 하나만 출력한다: {"name":"","type":"","look":"","why":""}`;
}

export { egoPrompt };
